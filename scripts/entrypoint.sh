#!/usr/bin/env bash
# Start the official vanilla Minecraft Java server after syncing to Mojang's latest release.
set -euo pipefail

DATA_DIR="${DATA_DIR:-/data}"
EULA="${EULA:-FALSE}"
VERSION="${VERSION:-LATEST}"
MEMORY="${MEMORY:-4G}"
INIT_MEMORY="${INIT_MEMORY:-$MEMORY}"
PUID="${PUID:-99}"
PGID="${PGID:-100}"
FETCH_ONLY="${FETCH_ONLY:-false}"
JVM_OPTS="${JVM_OPTS:-}"
LEVEL_NAME="${LEVEL_NAME:-world}"

cd /

reexec_as_player() {
  if [[ "$(id -u)" != "0" ]]; then
    return 0
  fi
  mkdir -p "$DATA_DIR"
  chown -R "${PUID}:${PGID}" "$DATA_DIR"
  echo "Dropping root (uid=${PUID} gid=${PGID})"
  exec setpriv --reuid="$PUID" --regid="$PGID" --clear-groups -- "$0" "$@"
}

accept_eula() {
  local v
  v="$(echo "$EULA" | tr '[:upper:]' '[:lower:]')"
  if [[ "$v" != "true" ]]; then
    echo "You must accept the Minecraft EULA to run this server:" >&2
    echo "  https://aka.ms/MinecraftEULA" >&2
    echo "Set EULA=TRUE on the container." >&2
    exit 1
  fi
  mkdir -p "$DATA_DIR"
  printf 'eula=true\n' > "${DATA_DIR}/eula.txt"
}

set_prop() {
  local key="$1" val="$2" file="${DATA_DIR}/server.properties"
  local escaped
  escaped="$(printf '%s' "$val" | sed 's/[&|\\]/\\&/g')"
  if grep -q "^${key}=" "$file" 2>/dev/null; then
    sed -i "s|^${key}=.*|${key}=${escaped}|" "$file"
  else
    printf '%s=%s\n' "$key" "$val" >> "$file"
  fi
}

set_from_env() {
  local env_name="$1" prop="$2"
  local val="${!env_name:-}"
  if [[ -n "$val" ]]; then
    set_prop "$prop" "$val"
  fi
}

